-- 002-care-plans.sql — additive extension: treatment plans, sessions, waiting list,
-- appointment types, refunds/adjustments and payment idempotency.
-- SAFE: only CREATE TABLE / ADD COLUMN / additive constraints. No data changes,
-- no drops, no rewrites of existing rows.

-- ---------------------------------------------------------------------------
-- Treatment plans
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS treatment_plans (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE CASCADE,
  patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft','pending_approval','approved','in_progress','completed','cancelled')),
  responsible_doctor_id INTEGER REFERENCES doctors(id) ON DELETE SET NULL,
  priority TEXT NOT NULL DEFAULT 'routine'
    CHECK (priority IN ('urgent','high','routine','low')),
  discount_cents INTEGER NOT NULL DEFAULT 0 CHECK (discount_cents >= 0),
  notes TEXT,
  revision_of INTEGER REFERENCES treatment_plans(id) ON DELETE SET NULL,
  created_by INTEGER REFERENCES users(id),
  approved_by INTEGER REFERENCES users(id),
  approved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_plans_patient ON treatment_plans(clinic_id, patient_id, status);

-- ---------------------------------------------------------------------------
-- Treatment sessions (phases) under a plan
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS treatment_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE CASCADE,
  plan_id INTEGER NOT NULL REFERENCES treatment_plans(id) ON DELETE CASCADE,
  position INTEGER NOT NULL DEFAULT 1,
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'planned'
    CHECK (status IN ('planned','scheduled','in_progress','completed','cancelled')),
  estimated_min INTEGER NOT NULL DEFAULT 0 CHECK (estimated_min >= 0),
  appointment_id INTEGER REFERENCES appointments(id) ON DELETE SET NULL,
  notes TEXT,
  completed_at TIMESTAMPTZ,
  completed_by INTEGER REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sessions_plan ON treatment_sessions(plan_id, position);

-- ---------------------------------------------------------------------------
-- Plan items (procedures). Tooth linkage uses the same FDI rules as the chart.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS treatment_plan_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE CASCADE,
  plan_id INTEGER NOT NULL REFERENCES treatment_plans(id) ON DELETE CASCADE,
  session_id INTEGER REFERENCES treatment_sessions(id) ON DELETE SET NULL,
  service_id INTEGER REFERENCES services(id) ON DELETE SET NULL,
  tooth_number INTEGER CHECK (
    tooth_number IS NULL OR
    ((tooth_number / 10 BETWEEN 1 AND 4 AND tooth_number % 10 BETWEEN 1 AND 8)
     OR (tooth_number / 10 BETWEEN 5 AND 8 AND tooth_number % 10 BETWEEN 1 AND 5))
  ),
  surfaces TEXT NOT NULL DEFAULT '',
  procedure_label TEXT NOT NULL,
  duration_min INTEGER NOT NULL DEFAULT 30 CHECK (duration_min > 0 AND duration_min <= 480),
  price_cents INTEGER NOT NULL DEFAULT 0 CHECK (price_cents >= 0),
  sequence INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'proposed'
    CHECK (status IN ('proposed','approved','scheduled','completed','cancelled','postponed')),
  dental_treatment_id INTEGER REFERENCES dental_treatments(id) ON DELETE SET NULL,
  completed_at TIMESTAMPTZ,
  completed_by INTEGER REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_plan_items_plan ON treatment_plan_items(plan_id, sequence);
CREATE INDEX IF NOT EXISTS idx_plan_items_session ON treatment_plan_items(session_id);

-- ---------------------------------------------------------------------------
-- Waiting list (patients wanting an earlier slot)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS waiting_list (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE CASCADE,
  patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE CASCADE,
  doctor_id INTEGER REFERENCES doctors(id) ON DELETE SET NULL,
  service_id INTEGER REFERENCES services(id) ON DELETE SET NULL,
  reason TEXT,
  status TEXT NOT NULL DEFAULT 'waiting'
    CHECK (status IN ('waiting','booked','cancelled')),
  booked_appointment_id INTEGER REFERENCES appointments(id) ON DELETE SET NULL,
  created_by INTEGER REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_waiting_clinic ON waiting_list(clinic_id, status, created_at);

-- ---------------------------------------------------------------------------
-- Appointments: type + session link (additive columns, backfilled defaults)
-- ---------------------------------------------------------------------------
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS appointment_type TEXT NOT NULL DEFAULT 'new_visit'
  CHECK (appointment_type IN ('new_visit','follow_up','consultation','procedure','emergency'));
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS treatment_session_id INTEGER
  REFERENCES treatment_sessions(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_appt_session ON appointments(treatment_session_id);

-- ---------------------------------------------------------------------------
-- Payments: refunds/adjustments + idempotency key
-- ---------------------------------------------------------------------------
ALTER TABLE payments ADD COLUMN IF NOT EXISTS type TEXT NOT NULL DEFAULT 'payment'
  CHECK (type IN ('payment','refund','adjustment'));
ALTER TABLE payments ADD COLUMN IF NOT EXISTS idempotency_key TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_idempotency
  ON payments(clinic_id, idempotency_key) WHERE idempotency_key IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Dental treatments: 'postponed' state (cancelled/postponed must never update
-- the chart). Additive: existing rows keep their statuses.
-- ---------------------------------------------------------------------------
ALTER TABLE dental_treatments DROP CONSTRAINT IF EXISTS dental_treatments_status_check;
ALTER TABLE dental_treatments ADD CONSTRAINT dental_treatments_status_check
  CHECK (status IN ('planned','completed','cancelled','postponed'));
