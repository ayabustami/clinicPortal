-- pg/011_email_verification.sql — one-time email verification codes.
-- Supports: password reset (forgot password), password change confirmation
-- (settings), and account setup invitations sent when an admin/owner adds a
-- staff account. Additive only — no existing table is touched.
--
-- Codes are stored as SHA-256 hashes (never plaintext), expire after a short
-- TTL, and are single-use with a bounded number of verification attempts.

CREATE TABLE email_verification_codes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  purpose TEXT NOT NULL CHECK (purpose IN ('password_reset', 'password_change', 'account_setup')),
  code_hash TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  consumed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Lookup path: latest unconsumed code for (email, purpose).
CREATE INDEX idx_ev_codes_lookup ON email_verification_codes (lower(email), purpose, consumed_at);
