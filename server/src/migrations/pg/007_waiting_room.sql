-- 007_waiting_room.sql
-- Same-day Waiting Room queue: who is physically in the clinic right now.
-- Distinct from waiting_list (patients requesting an earlier slot) and from
-- appointments (the booking record). An entry MAY reference an appointment
-- (check-in sync, or a late arrival after a recorded no-show) but never
-- modifies it: a no_show appointment stays no_show forever.
-- Additive migration: new table + indexes only, no existing data touched.
CREATE TABLE IF NOT EXISTS waiting_room (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE CASCADE,
  branch_id INTEGER REFERENCES branches(id) ON DELETE SET NULL,
  patient_id INTEGER NOT NULL REFERENCES patients(id),
  doctor_id INTEGER NOT NULL REFERENCES doctors(id),
  appointment_id INTEGER REFERENCES appointments(id) ON DELETE SET NULL,
  visit_type TEXT NOT NULL DEFAULT 'new_visit'
    CHECK (visit_type IN ('new_visit','follow_up','consultation','procedure','emergency')),
  reason TEXT,
  status TEXT NOT NULL DEFAULT 'waiting'
    CHECK (status IN ('waiting','called','in_treatment','completed','left')),
  arrived_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  called_at TIMESTAMPTZ,
  started_at TIMESTAMPTZ,
  ended_at TIMESTAMPTZ,
  created_by INTEGER REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_wr_clinic_status ON waiting_room(clinic_id, status, arrived_at);
CREATE INDEX IF NOT EXISTS idx_wr_appt ON waiting_room(appointment_id);

-- One active (not completed / not left) queue entry per patient per clinic:
-- a patient cannot be waiting twice at the same time.
CREATE UNIQUE INDEX IF NOT EXISTS uq_wr_one_active_per_patient
  ON waiting_room(clinic_id, patient_id)
  WHERE status IN ('waiting', 'called', 'in_treatment');
