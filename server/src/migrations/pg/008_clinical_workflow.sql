-- 008_clinical_workflow.sql
-- Clinical workflow re-engineering, stage 1 (additive only):
--
--  1. Service catalog configuration: category, workflow requirement flags and
--     booking metadata so services drive their own clinical workflow instead
--     of every component assuming one fixed path.
--  2. Multi-service appointments: appointment_services junction with per-line
--     duration and a price snapshot taken at booking time (historical
--     appointments keep their original values when the catalog changes).
--     appointments.service_id remains the primary service for compatibility.
--  3. Finalized clinical documentation: finalized_at/by on medical_records and
--     an append-only amendment log so signed notes are preserved and every
--     post-finalization change is recorded with its author and reason.
--  4. Performed-procedure integrity: at most one COMPLETED procedure per
--     encounter + tooth + procedure (+surfaces), preventing duplicate
--     performed records (and therefore duplicate charges) at the database level.
--
-- No existing data is modified except the backfill of appointment_services
-- from appointments.service_id (pure copy of existing facts).

ALTER TABLE services
  ADD COLUMN IF NOT EXISTS category TEXT,
  ADD COLUMN IF NOT EXISTS preparation TEXT,
  ADD COLUMN IF NOT EXISTS provider_qualification TEXT,
  ADD COLUMN IF NOT EXISTS requires_encounter SMALLINT NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS requires_chart SMALLINT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS requires_plan_item SMALLINT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS requires_performed SMALLINT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS requires_imaging SMALLINT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS requires_followup SMALLINT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS bills_item SMALLINT NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS appointment_services (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE CASCADE,
  appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
  service_id INTEGER NOT NULL REFERENCES services(id),
  sequence INTEGER NOT NULL DEFAULT 1,
  duration_min INTEGER NOT NULL CHECK (duration_min > 0 AND duration_min <= 480),
  price_cents INTEGER NOT NULL DEFAULT 0 CHECK (price_cents >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (appointment_id, service_id)
);
CREATE INDEX IF NOT EXISTS idx_appt_services_appt ON appointment_services(appointment_id, sequence);
CREATE INDEX IF NOT EXISTS idx_appt_services_svc ON appointment_services(service_id);

-- Backfill: every existing appointment keeps exactly its current service.
INSERT INTO appointment_services (clinic_id, appointment_id, service_id, sequence, duration_min, price_cents)
SELECT a.clinic_id, a.id, a.service_id, 1, a.duration_min, COALESCE(s.price_cents, 0)
FROM appointments a
LEFT JOIN services s ON s.id = a.service_id
WHERE a.service_id IS NOT NULL
ON CONFLICT (appointment_id, service_id) DO NOTHING;

ALTER TABLE medical_records
  ADD COLUMN IF NOT EXISTS finalized_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS finalized_by INTEGER REFERENCES users(id);

-- Existing approved records are treated as finalized at their last update.
UPDATE medical_records
   SET finalized_at = COALESCE(finalized_at, updated_at),
       finalized_by = COALESCE(finalized_by, created_by)
 WHERE status = 'approved' AND finalized_at IS NULL;

CREATE TABLE IF NOT EXISTS record_amendments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE CASCADE,
  record_id INTEGER NOT NULL REFERENCES medical_records(id) ON DELETE CASCADE,
  amended_by INTEGER REFERENCES users(id),
  amended_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reason TEXT NOT NULL,
  changes TEXT NOT NULL   -- JSON object: field -> {before, after}
);
CREATE INDEX IF NOT EXISTS idx_amendments_record ON record_amendments(record_id, amended_at);

-- One performed (completed) procedure per encounter/tooth/procedure/surfaces.
CREATE UNIQUE INDEX IF NOT EXISTS uq_performed_once
  ON dental_treatments (record_id, tooth_number, procedure, surfaces)
  WHERE status = 'completed' AND record_id IS NOT NULL;
