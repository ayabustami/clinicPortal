const LangCtx = createContext({ lang: 'en', dir: 'ltr', setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('cmp_lang') : null;
    return saved === 'ar' ? 'ar' : 'en';
  });
  const dir = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    try { localStorage.setItem('cmp_lang', lang); } catch { /* private mode */ }
  }, [lang, dir]);

  const setLang = useCallback((l) => setLangState(l === 'ar' ? 'ar' : 'en'), []);
  const t = useCallback((key) => DICT[lang]?.[key] ?? DICT.en[key] ?? key, [lang]);
  const value = useMemo(() => ({ lang, dir, setLang, t }), [lang, dir, setLang, t]);
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export const useI18n = () => useContext(LangCtx);
